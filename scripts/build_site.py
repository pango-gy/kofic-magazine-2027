#!/usr/bin/env python3
"""Build the parts of the site that depend on which articles and issues exist.

    python3 scripts/build_site.py

Source of truth
    data/site.json          current issue, list of issues (newest first), sections
    data/<issue>.json       one file per issue: label, title, articles (in reading order)
    <issue>/index.html      that issue's main page, written by hand
    <issue>/*.html          the article pages, written by hand (or by their own scripts)

What this writes
    assets/js/issue-data.js   the same data for the browser (prev/next, list page)
    list.html                 the article cards, for every issue      (between markers)
    index.html                a copy of the current issue's main page, paths rewritten
    every page                the drawer contents (between markers), the issue label in
                              the header, article counts, the issue-data.js script tag,
                              and one cache-busting ?v= on the shared css/js
    <issue>/index.html        the News rows on the main page           (between markers)
    <issue>/production/*      via scripts/build_films.py, when the issue has production.html

To publish a new issue: see README.md.
"""
import glob
import html
import json
import os
import re
import subprocess
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
esc = lambda s: html.escape(s, quote=False)
attr = lambda s: html.escape(s, quote=True)


def read(path):
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        return f.read()


def write(path, text):
    full = os.path.join(ROOT, path)
    old = None
    if os.path.exists(full):
        with open(full, encoding="utf-8") as f:
            old = f.read()
    if old != text:
        with open(full, "w", encoding="utf-8") as f:
            f.write(text)
        return True
    return False


def between(text, name, new, indent=""):
    """Replace what sits between <!-- name:start --> and <!-- name:end -->."""
    a, b = f"<!-- {name}:start -->", f"<!-- {name}:end -->"
    i, j = text.find(a), text.find(b)
    if i < 0 or j < 0:
        raise SystemExit(f"markers for '{name}' not found")
    return text[: i + len(a)] + "\n" + new.rstrip("\n") + "\n" + indent + text[j:]


# --------------------------------------------------------------------------- data
SITE = json.loads(read("data/site.json"))
ISSUES = [json.loads(read(f"data/{i}.json")) for i in SITE["issues"]]
BY_ID = {i["id"]: i for i in ISSUES}
CURRENT = BY_ID[SITE["current"]]
SECTIONS = [s["id"] for s in SITE["sections"]]
BUILD = time.strftime("%Y%m%d%H%M%S")


def base_section(sec):
    return "GLOBAL" if sec.startswith("GLOBAL") else sec


def list_href(prefix, issue, section=None, corner=None):
    q = []
    if issue["id"] != CURRENT["id"]:
        q.append("issue=" + issue["id"])
    if section:
        q.append("section=" + section.replace(" ", "%20"))
    if corner:
        q.append("corner=" + corner.replace(" ", "%20"))
    return f"{prefix}list.html" + ("?" + "&amp;".join(q) if q else "")


# --------------------------------------------------------------------------- browser data
def write_issue_data():
    out = {
        "current": CURRENT["id"],
        "sections": SITE["sections"],
        "issues": [
            {
                "id": i["id"], "label": i["label"], "title": i.get("title", i["label"]),
                "main": os.path.exists(os.path.join(ROOT, i["id"], "index.html")),
                "articles": [
                    {k: a[k] for k in ("file", "section", "label", "title", "shortTitle", "sub", "corner", "search") if a.get(k)}
                    for a in i["articles"]
                ],
            }
            for i in ISSUES
        ],
    }
    js = "/* Generated by scripts/build_site.py from data/*.json — do not edit. */\n" \
         "window.KOFIC = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n"
    return write("assets/js/issue-data.js", js)


# --------------------------------------------------------------------------- list cards
def kicker_html(a):
    label = a.get("label") or a["section"]
    if a.get("lang"):
        head = f'{esc(base_section(a["section"]))} <span class="lang-tag">{esc(a["lang"])}</span>'
    elif a.get("corner") and label.endswith(" · " + a["corner"]):
        head = f'{esc(label[: -len(a["corner"])])}<span class="ed-corner">{esc(a["corner"])}</span>'
    else:
        head = esc(label)
    return f'{head} <span class="ed-date">{a["date"].replace("-", ".")}</span>'


def card_html(issue, a):
    data = f' data-issue="{issue["id"]}"'
    if a.get("corner"):
        data += f' data-corner="{attr(a["corner"])}"'
    data += f' data-section="{attr(a["section"])}" data-date="{a["date"]}" data-search="{attr(a.get("search", ""))}"'
    foot = f'<span>{esc(a["by"])}</span>' if a.get("by") else "<span></span>"
    foot += f'<span>{esc(a["kind"])}</span>' if a.get("kind") else ""
    return f'''                    <a href="./{issue["id"]}/{a["file"]}" class="archive-card"{data}>
                        <div class="ed-media"><img src="./assets/images/{a["image"]}" alt="{attr(a.get("imageAlt", a["title"]))}" loading="lazy"></div>
                        <div class="archive-card-body">
                            <p class="ed-kicker">{kicker_html(a)}</p>
                            <h2 class="ed-card-title">{esc(a["title"])}</h2>
                            <p class="ed-card-deck">{esc(a.get("deck", ""))}</p>
                            <div class="archive-card-foot">{foot}</div>
                        </div>
                    </a>
'''


def build_list(text):
    cards = "\n".join(card_html(i, a) for i in ISSUES for a in i["articles"])
    return between(text, "cards", cards, "                    ")


# --------------------------------------------------------------------------- drawer
def drawer_html(issue, prefix, pad="                "):
    groups = []
    for sec in SECTIONS:
        arts = [a for a in issue["articles"] if base_section(a["section"]) == sec]
        if not arts:
            continue
        links = "\n".join(
            f'{pad}        <a href="{prefix}{issue["id"]}/{a["file"]}"><strong>{esc(a.get("shortTitle") or a["title"])}</strong>'
            f'<span>{esc((a["corner"] + " · " if a.get("corner") else "") + (a.get("sub") or ""))}</span></a>'
            for a in arts
        )
        groups.append(
            f'{pad}<div class="ed-drawer-group">\n'
            f'{pad}    <h3>{esc(sec)} <a href="{list_href(prefix, issue, sec)}">전체 →</a></h3>\n'
            f'{pad}    <div class="ed-drawer-links">\n{links}\n{pad}    </div>\n'
            f'{pad}</div>'
        )
    return "\n".join(groups)


def add_drawer_markers(text):
    """One-time migration: wrap the drawer body's contents in markers."""
    if "<!-- drawer:start -->" in text:
        return text
    key = '<div class="ed-drawer-body">'
    i = text.find(key)
    if i < 0:
        return text
    j, depth, pos = i + len(key), 1, i + len(key)
    for m in re.finditer(r"<(/?)div\b", text[pos:]):
        depth += -1 if m.group(1) else 1
        if depth == 0:
            j = pos + m.start()
            break
    return text[: i + len(key)] + "\n                <!-- drawer:start -->\n                <!-- drawer:end -->\n            " + text[j:]


# --------------------------------------------------------------------------- shared touches
def common(text, path, issue):
    """Things every page gets: drawer, header label, counts, script tag, versions."""
    depth = path.count("/")
    prefix = "../" * depth or "./"
    text = add_drawer_markers(text)
    if "<!-- drawer:start -->" in text:
        text = between(text, "drawer", drawer_html(issue, prefix), "                ")
    # header: which issue this page belongs to
    text = re.sub(r'(<span class="mk-issue-label">)[^<]*(</span>)', r"\g<1>" + issue["label"] + r"\g<2>", text)
    # drawer heading and the button that opens it name the issue too
    month = re.sub(r"^\d+년\s*", "", issue["label"])
    text = re.sub(r'(<span>ISSUE INDEX · VOL\. )[\d.]+(</span>\s*)[^<]*?전체 목차',
                  r"\g<1>" + issue["id"].replace("-", ".") + r"\g<2>" + issue["label"] + " 전체 목차", text)
    text = re.sub(r'aria-label="[^"]*전체 목차 및 검색"', f'aria-label="{issue["label"]} 전체 목차 및 검색"', text)
    text = re.sub(r'aria-label="메뉴와 [^"]*목차 열기"', f'aria-label="메뉴와 {month} 목차 열기"', text)
    text = re.sub(r"(웹진 〈한국영화〉 )\d+년 \d+월호", r"\g<1>" + issue["label"], text)
    text = re.sub(r"\d+년 \d+월호( · 총 \d+편 수록)", issue["label"] + r"\1", text)
    # article counts
    n = len(issue["articles"])
    text = re.sub(r'(href="[^"]*list\.html[^"]*">)전체 \d+편 보기', r"\g<1>" + f"전체 {n}편 보기", text)
    text = re.sub(r"총 \d+편 수록", f"총 {n}편 수록", text)
    # section links carry the issue when it is not the current one
    text = re.sub(r'list\.html\?issue=[\w-]+&(?:amp;)?', "list.html?", text)
    text = re.sub(r'list\.html\?issue=[\w-]+"', 'list.html"', text)
    if issue["id"] != CURRENT["id"]:
        text = text.replace("list.html?section=", f'list.html?issue={issue["id"]}&amp;section=')
        text = re.sub(r'(href="[^"]*list\.html)"', r'\1?issue=' + issue["id"] + '"', text)
    # issue data for the browser, loaded before the page scripts
    if "issue-data.js" not in text:
        text = re.sub(r'(\n[ \t]*)(<script defer src="[^"]*assets/js/magazine-2027\.js)',
                      r'\1<script defer src="' + prefix + r'assets/js/issue-data.js"></script>\1\2', text, count=1)
    # one cache-busting stamp for the shared files
    text = re.sub(r'((?:layout-2027|magazine-2027)\.(?:css|js)|issue-data\.js)(\?v=\w+)?"', r'\1?v=' + BUILD + '"', text)
    return text


# --------------------------------------------------------------------------- issue main page
def news_rows(issue, pad="                        "):
    arts = [a for a in issue["articles"] if a["section"] == "NEWS"]
    arts.sort(key=lambda a: a["date"], reverse=True)
    rows = []
    for a in arts[:4]:
        kind = f'<b>{esc(a["corner"])}</b>' if a.get("corner") else ""
        rows.append(
            f'{pad}<li>\n'
            f'{pad}    <a class="mk-news-item" href="./{a["file"]}">\n'
            f'{pad}        <span class="mk-news-meta"><time datetime="{a["date"]}">{a["date"].replace("-", ".")}</time>{kind}</span>\n'
            f'{pad}        <span class="mk-news-title">{esc(a["title"])}</span>\n'
            f'{pad}        <span class="mk-news-photo"><img src="../assets/images/{a["image"]}" alt="" width="900" height="600" loading="lazy" decoding="async"></span>\n'
            f'{pad}    </a>\n'
            f'{pad}</li>'
        )
    return "\n".join(rows)


def to_root(text, issue_id):
    """An issue's main page lives in <issue>/; the root index.html is the same page one level up."""
    text = text.replace("../assets/", "./assets/")
    text = re.sub(r'(href|src)="\./(?!assets/)', r'\1="./' + issue_id + "/", text)
    text = text.replace('"../list.html', '"./list.html').replace('"../index.html', '"./index.html')
    text = text.replace(f'"../{issue_id}/', f'"./{issue_id}/')
    return text


# --------------------------------------------------------------------------- run
def main():
    changed = []
    if write_issue_data():
        changed.append("assets/js/issue-data.js")

    for issue in ISSUES:
        iid = issue["id"]
        main_page = f"{iid}/index.html"
        if os.path.exists(os.path.join(ROOT, main_page)):
            text = read(main_page)
            if "<!-- news:start -->" in text:
                text = between(text, "news", news_rows(issue), "                    ")
            if write(main_page, common(text, main_page, issue)):
                changed.append(main_page)
        if os.path.exists(os.path.join(ROOT, iid, "production.html")):
            subprocess.run([sys.executable, os.path.join(ROOT, "scripts", "build_films.py"), iid],
                           cwd=ROOT, check=True, stdout=subprocess.DEVNULL)
        for full in sorted(glob.glob(os.path.join(ROOT, iid, "**", "*.html"), recursive=True)):
            path = os.path.relpath(full, ROOT)
            if path == main_page:
                continue
            if write(path, common(read(path), path, issue)):
                changed.append(path)

    # root: the current issue's main page, and the list of every issue
    cur_main = f'{CURRENT["id"]}/index.html'
    if os.path.exists(os.path.join(ROOT, cur_main)):
        if write("index.html", to_root(read(cur_main), CURRENT["id"])):
            changed.append("index.html")
    if write("list.html", common(build_list(read("list.html")), "list.html", CURRENT)):
        changed.append("list.html")

    total = sum(len(i["articles"]) for i in ISSUES)
    print(f"issues: {len(ISSUES)} (current {CURRENT['id']}), articles: {total}, build {BUILD}")
    print(f"files changed: {len(changed)}")


if __name__ == "__main__":
    main()
